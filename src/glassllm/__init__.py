__version__ = "0.1.0"

LANGUAGES = ("pt", "en")


def load_pretrained(lang: str, model_dir: str | Path | None = None) -> tuple[GlassLM, Tokenizer]:
    """Load a language's weights and tokenizer from a directory or package resources.

    Packaged assets must have been generated by the training scripts. A checkout
    without those assets raises FileNotFoundError; it does not synthesize weights.
    """
    if lang not in LANGUAGES:
        raise ValueError(f"unknown language {lang!r}; choose one of {', '.join(LANGUAGES)}")
    base = Path(model_dir) if model_dir is not None else resources.files("glassllm") / "weights"
    weights, vocab = base / f"{lang}.npz", base / f"{lang}.tokenizer.json"
    if not (weights.is_file() and vocab.is_file()):
        raise FileNotFoundError(f"pretrained files for {lang!r} not found in {base}")
    # Traversables need not be filesystem paths (for example in a zip package).
    with resources.as_file(weights) as weights_path, resources.as_file(vocab) as vocab_path:
        model, tokenizer = GlassLM.load(weights_path), Tokenizer.load(vocab_path)
    if model.cfg.vocab_size != tokenizer.vocab_size:
        raise ValueError(f"pretrained model and tokenizer vocab sizes differ for {lang!r}")
    return model, tokenizer


